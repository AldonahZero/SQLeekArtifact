BEGIN;
CREATE TYPE INT AS (a int, b text);
CREATE TYPE TEXT AS (x int, y text);
CREATE TABLE t (c INT);
CREATE FUNCTION trigfunc() RETURNS trigger AS $$
BEGIN
  NEW.c := ROW((NEW.c).a, (NEW.c).b)::TEXT;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg BEFORE INSERT ON t FOR EACH ROW EXECUTE FUNCTION trigfunc();
INSERT INTO t VALUES (ROW(1, 'hello')::INT);
ALTER TABLE t RENAME TRIGGER trg TO trg_new;
ALTER TYPE INT RENAME TO INT;
DECLARE cur CURSOR FOR SELECT c FROM t;
FETCH cur;
COMMIT;
